pub const fn lit_pixels(c: u8) -> u32 {
    let g = glyph(c);
    let mut n = 0;
    let mut i = 0;
    while i < 5 {
        n += (g[i] & 0x7F).count_ones();
        i += 1;
    }
    n
}
