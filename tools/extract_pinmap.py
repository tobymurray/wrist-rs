#!/usr/bin/env python3
"""Generate pins.rs from the pins and nets on UNAcore sheet 2.

Takes the schematic PDF from UNAWatch/una-hardware and needs pdftotext (poppler); writes
the Rust source to stdout.

    curl -LO "https://raw.githubusercontent.com/UNAWatch/una-hardware/main/una-watch/electronics/UNAcore/UNAcore%20Rev3.2%20Schematic.pdf"
    extract_pinmap.py "UNAcore Rev3.2 Schematic.pdf" > crates/wrist-board/src/pins.rs
"""
import re
import subprocess
import sys
from collections import defaultdict

NET_ABOVE_PIN = 3.1
ROW_TOLERANCE = 1.6
PIN = re.compile(r"P[A-H]\d{1,2}")
BALL = re.compile(r"[A-M]\d{1,2}")
NET = re.compile(r"[A-Z][A-Z0-9_]{2,}")


def words(pdf):
    html = subprocess.run(
        ["pdftotext", "-f", "2", "-l", "2", "-bbox", pdf, "-"],
        check=True, capture_output=True, text=True,
    ).stdout
    found = re.findall(
        r'<word xMin="([\d.]+)" yMin="([\d.]+)" xMax="([\d.]+)" yMax="([\d.]+)">([^<]*)</word>',
        html,
    )
    return [(float(a), float(b), float(c), float(d), t) for a, b, c, d, t in found]


def centre(w):
    return (w[1] + w[3]) / 2


def pin_map(ws):
    is_net = lambda t: NET.fullmatch(t) and not BALL.fullmatch(t)
    mapping = {}
    for p in (w for w in ws if PIN.fullmatch(w[4]) and w[0] < 270):
        left = p[0] < 200
        near = [
            w for w in ws
            if is_net(w[4])
            and abs(centre(w) + NET_ABOVE_PIN - centre(p)) < ROW_TOLERANCE
            and ((left and 100 < w[0] < 190) or (not left and 270 < w[0] < 340))
        ]
        if len(near) > 1:
            sys.exit(f"{p[4]}: more than one net on the row: {[w[4] for w in near]}")
        if near:
            mapping[p[4]] = near[0][4]
    return mapping


def interrupt_table(ws):
    rows = defaultdict(list)
    for w in ws:
        if 480 < w[0] < 600 and 40 < centre(w) < 160:
            rows[round(centre(w))].append(w)
    table = {}
    for row in rows.values():
        row.sort()
        if len(row) == 2 and PIN.fullmatch(row[1][4]):
            table[row[1][4]] = row[0][4]
    return table


def main(pdf):
    ws = words(pdf)
    mapping = pin_map(ws)
    anchors = interrupt_table(ws)
    if len(anchors) < 15:
        sys.exit(f"read only {len(anchors)} rows of the interrupt table")
    wrong = {p: (n, mapping.get(p)) for p, n in anchors.items() if mapping.get(p) != n}
    if wrong:
        sys.exit(f"disagrees with the schematic's interrupt table: {wrong}")
    nets = [n for n in mapping.values()]
    if len(set(nets)) != len(nets):
        sys.exit("a net is assigned to two pins")
    key = lambda p: (p[1], int(p[2:]))
    print("// Generated by tools/extract_pinmap.py from UNAcore Rev3.2 sheet 2.")
    print("// Schematic by Una Watch Ltd, CC BY 4.0: https://github.com/UNAWatch/una-hardware\n")
    print("use super::{pin, Pin, Port::{A, B, C, D, E, F, G}};\n")
    for p in sorted(mapping, key=key):
        print(f"pub const {mapping[p]}: Pin = pin({p[1]}, {int(p[2:])});")


main(sys.argv[1])
